/// Acceptance 7: lshape not on the path is said, by name, and nothing is written — and the
/// declaration a first run left behind does not stand in for it on a rerun.
#[test]
fn it_refuses_when_lshape_is_not_on_the_path_and_writes_nothing() {
    let root = common::tempdir("htl-cli-shapes", "no-lshape");
    write(&root.join("htl.toml"), "[check]\n");
    write(&root.join("src/main.tl"), MAIN);
    let refusal = "shapes: lshape is not on the path (no Lua or Teal module answers require(\"lshape\")); vendor or install it, then rerun\n";
    let out = htl(&root, &["shapes"]);
    assert_eq!(out.status.code(), Some(1), "{}", stderr(&out));
    assert_eq!(stderr(&out), refusal);
    assert!(!root.join("src/shapes").exists());
    assert!(!root.join("types").exists());

    // With it vendored the run writes; remove it and change the record: the declaration
    // `types/lshape.d.tl` is on the path now, and is not an implementation.
    vendor_lshape(&root);
    assert_eq!(htl(&root, &["shapes"]).status.code(), Some(0));
    assert!(root.join("types/lshape.d.tl").exists());
    std::fs::remove_dir_all(root.join("src/lshape")).unwrap();
    write(
        &root.join("src/main.tl"),
        &MAIN.replace(
            "      n: integer\n",
            "      n: integer\n      extra: string\n",
        ),
    );
    let out = htl(&root, &["shapes"]);
    assert_eq!(out.status.code(), Some(1), "{}", stderr(&out));
    assert_eq!(stderr(&out), refusal);
    assert_eq!(
        read(&root.join("src/shapes/main.lua")),
        MAIN_LUA,
        "the shapes written before are not rewritten"
    );
}


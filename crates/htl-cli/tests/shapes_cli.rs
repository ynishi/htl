//! `htl shapes`, driven through the binary on a temp project: what it writes and where, what
//! it says on stderr, when it exits non-zero, and that the shapes it writes work — the
//! checker narrows through them and the lshape they are written against checks a value.
//!
//! The project carries lshape the way a user would: vendored under `src/lshape/`, so that
//! `require("lshape")` is `src/lshape/init.lua` (the files are `tests/fixtures/lshape/`, with
//! the README saying where they come from). Nothing here needs a network.

use std::collections::BTreeSet;
use std::path::Path;
use std::process::{Command, Output};

mod common;

fn write(path: &Path, text: &str) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, text).unwrap();
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

fn htl(root: &Path, args: &[&str]) -> Output {
    Command::new(common::htl_bin())
        .args(args)
        .current_dir(root)
        .output()
        .unwrap()
}

fn stderr(out: &Output) -> String {
    String::from_utf8_lossy(&out.stderr).into_owned()
}

/// Copy the vendored lshape into the project as `src/lshape/`: its `.lua` files only.
fn vendor_lshape(root: &Path) {
    let from = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/lshape");
    for e in std::fs::read_dir(from).unwrap() {
        let path = e.unwrap().path();
        if path.extension().is_some_and(|x| x == "lua") {
            write(
                &root.join("src/lshape").join(path.file_name().unwrap()),
                &read(&path),
            );
        }
    }
}

/// The module of acceptance 1: `Request` with a required `id` and `n`, an optional `tags`.
const MAIN: &str = "local record M
   record Request
      id: string
      n: integer
      tags: {string}   ---@optional
   end
end
return M
";

/// A project whose `src/main.tl` is [`MAIN`], with lshape vendored.
fn project(name: &str) -> common::TempDir {
    let root = common::tempdir("htl-cli-shapes", name);
    write(&root.join("htl.toml"), "[check]\n");
    write(&root.join("src/main.tl"), MAIN);
    vendor_lshape(&root);
    root
}

const MAIN_LUA: &str =
    "-- Generated by htl shapes from src/main.tl. The record is the source; do not edit.
local T = require(\"lshape\").t
local M = {}

M.Request = T.shape({
   id = T.string,
   n = T.integer,
   tags = T.array_of(T.string):is_optional(),
}, { open = false })

return M
";

const MAIN_DTL: &str =
    "-- Generated by htl shapes from src/main.tl. The record is the source; do not edit.
-- Assert from another module: this file requires \"main\", so \"main\" cannot require it.
local lshape = require(\"lshape\")
local type main = require(\"main\")
local record shapes_main
   Request: lshape.Schema<main.Request>
end
return shapes_main
";

fn mtime(path: &Path) -> std::time::SystemTime {
    std::fs::metadata(path).unwrap().modified().unwrap()
}

/// Acceptance 1: the three files, their text, the three lines said; run again, nothing is
/// written, and the files are not touched.
#[test]
fn it_writes_the_shapes_and_their_declaration_and_then_leaves_them_be() {
    let root = project("one");
    let out = htl(&root, &["shapes"]);
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
    assert_eq!(
        stderr(&out),
        "shapes: wrote src/shapes/main.lua
shapes: wrote types/shapes/main.d.tl
shapes: wrote types/lshape.d.tl
"
    );
    assert_eq!(read(&root.join("src/shapes/main.lua")), MAIN_LUA);
    assert_eq!(read(&root.join("types/shapes/main.d.tl")), MAIN_DTL);
    assert_eq!(
        read(&root.join("types/lshape.d.tl")),
        htl::shapes::LSHAPE_DTL
    );

    let files = [
        root.join("src/shapes/main.lua"),
        root.join("types/shapes/main.d.tl"),
        root.join("types/lshape.d.tl"),
    ];
    let before: Vec<_> = files.iter().map(|f| mtime(f)).collect();
    std::thread::sleep(std::time::Duration::from_millis(20));
    let again = htl(&root, &["shapes"]);
    assert_eq!(again.status.code(), Some(0), "{}", stderr(&again));
    assert_eq!(
        stderr(&again),
        "shapes: current src/shapes/main.lua
shapes: current types/shapes/main.d.tl
shapes: current types/lshape.d.tl
"
    );
    let after: Vec<_> = files.iter().map(|f| mtime(f)).collect();
    assert_eq!(before, after, "an unchanged file is not rewritten");
}


/// Acceptance 2: a module that asserts a value through the generated shape is checked clean,
/// and the record comes back typed — a wrong use of a field is the checker's error, at its line.
#[test]
fn the_checker_narrows_through_the_generated_declaration() {
    let root = project("check");
    assert_eq!(htl(&root, &["shapes"]).status.code(), Some(0));
    let boundary = |tail: &str| {
        format!(
            "local lshape = require(\"lshape\")
local main = require(\"main\")
local S = require(\"shapes.main\")

local function read(v: any): string
   local r: main.Request = lshape.check.assert(v, S.Request)
{tail}   return r.id
end

return read
"
        )
    };
    write(&root.join("src/use.tl"), &boundary(""));
    let out = htl(&root, &["check", ".", "--no-cache"]);
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
    assert!(stderr(&out).contains("0 error(s)"), "{}", stderr(&out));

    write(
        &root.join("src/use.tl"),
        &boundary("   local bad: integer = r.id\n"),
    );
    let out = htl(&root, &["check", ".", "--no-cache"]);
    assert_eq!(out.status.code(), Some(1), "{}", stderr(&out));
    assert!(
        stderr(&out)
            .contains("src/use.tl:7:26: in local declaration: bad: got string, expected integer"),
        "{}",
        stderr(&out)
    );
}

/// Acceptance 3: the generated Lua loads under `htl test`, against the real lshape, and a
/// value that passes comes back while one that fails raises, with a reason naming `id`.
#[test]
fn a_value_is_checked_at_run_time_against_the_generated_shape() {
    let root = project("test");
    assert_eq!(htl(&root, &["shapes"]).status.code(), Some(0));
    write(
        &root.join("tests/round_trip_test.tl"),
        "local t = require(\"htl.test\")
local lshape = require(\"lshape\")
local S = require(\"shapes.main\")

t.it(\"a value that passes is handed back\", function()
   local r = lshape.check.assert({ id = \"a\", n = 1 }, S.Request)
   t.expect(r.id):to_equal(\"a\")
end)

t.it(\"an optional field may be left out and a listed one is checked\", function()
   local ok = lshape.check.check({ id = \"a\", n = 1, tags = { \"x\" } }, S.Request)
   t.expect(ok):to_equal(true)
   local bad = lshape.check.check({ id = \"a\", n = 1, tags = { 1 } }, S.Request)
   t.expect(bad):to_equal(false)
end)

t.it(\"a key the record does not declare is refused\", function()
   local ok = lshape.check.check({ id = \"a\", n = 1, extra = true }, S.Request)
   t.expect(ok):to_equal(false)
end)

t.it(\"a value that fails raises, and the reason names the field\", function()
   local ok, err = pcall(function(): string
      return lshape.check.assert({ id = 1, n = 1 }, S.Request).id
   end)
   t.expect(ok):to_equal(false)
   t.expect(tostring(err)):to_match(\"%$%.id\")
end)
",
    );
    let out = htl(&root, &["test", "."]);
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
    assert!(
        stderr(&out).contains("4 passed, 0 failed"),
        "{}",
        stderr(&out)
    );
}


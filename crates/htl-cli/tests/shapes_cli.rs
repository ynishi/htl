/// A second module with one record, and its two generated files written by a first run.
fn project_with_extra(name: &str) -> common::TempDir {
    let root = project(name);
    write(
        &root.join("src/extra.tl"),
        "local record extra
   record Item
      n: integer
   end
end
return extra
",
    );
    let out = htl(&root, &["shapes"]);
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
    assert!(root.join("src/shapes/extra.lua").exists());
    assert!(root.join("types/shapes/extra.d.tl").exists());
    root
}

/// The module `extra` once its records are deleted: it declares nothing to lower.
const EXTRA_EMPTY: &str = "local record extra
end
return extra
";

/// A module whose records are all deleted loses the files an earlier run wrote for it, and
/// each removal is said; the other modules are not touched.
#[test]
fn the_files_of_a_module_with_no_records_left_are_removed() {
    let root = project_with_extra("removed");
    write(&root.join("src/extra.tl"), EXTRA_EMPTY);
    let out = htl(&root, &["shapes"]);
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
    let err = stderr(&out);
    assert!(
        err.contains("shapes: removed src/shapes/extra.lua\n"),
        "{err}"
    );
    assert!(
        err.contains("shapes: removed types/shapes/extra.d.tl\n"),
        "{err}"
    );
    assert_eq!(err.matches("removed").count(), 2, "{err}");
    assert!(!root.join("src/shapes/extra.lua").exists());
    assert!(!root.join("types/shapes/extra.d.tl").exists());
    assert_eq!(read(&root.join("src/shapes/main.lua")), MAIN_LUA);

    // Nothing left to remove: nothing is said.
    let again = htl(&root, &["shapes"]);
    assert_eq!(again.status.code(), Some(0), "{}", stderr(&again));
    assert!(!stderr(&again).contains("removed"), "{}", stderr(&again));
}

/// A module that is refused after it was written keeps its earlier files, which still
/// validate against the old shape: the run says they are stale, and fails.
#[test]
fn the_files_of_a_module_that_is_refused_now_are_said_to_be_stale() {
    let root = project_with_extra("stale");
    let lua_before = read(&root.join("src/shapes/extra.lua"));
    let dtl_before = read(&root.join("types/shapes/extra.d.tl"));
    write(
        &root.join("src/extra.tl"),
        "local interface Tagged
   n: integer
end
local record extra
   record Item is Tagged
   end
end
return extra
",
    );
    let out = htl(&root, &["shapes"]);
    assert_eq!(out.status.code(), Some(1), "{}", stderr(&out));
    let err = stderr(&out);
    assert!(
        err.contains("`extra.Item` takes fields from an interface (`is`); not lowered yet"),
        "{err}"
    );
    for stale in ["src/shapes/extra.lua", "types/shapes/extra.d.tl"] {
        let line =
            format!("shapes: {stale} left as it was and is stale: the module is refused above\n");
        assert!(err.contains(&line), "{err}");
    }
    // After the problems, not before.
    assert!(
        err.find("not lowered yet").unwrap() < err.find("is stale").unwrap(),
        "{err}"
    );
    assert_eq!(read(&root.join("src/shapes/extra.lua")), lua_before);
    assert_eq!(read(&root.join("types/shapes/extra.d.tl")), dtl_before);

    // A refused module that was never written has nothing stale to say.
    let fresh = project("never-written");
    write(
        &fresh.join("src/extra.tl"),
        "local interface Tagged
   n: integer
end
local record extra
   record Item is Tagged
   end
end
return extra
",
    );
    let out = htl(&fresh, &["shapes"]);
    assert_eq!(out.status.code(), Some(1), "{}", stderr(&out));
    assert!(!stderr(&out).contains("stale"), "{}", stderr(&out));
}

/// A file in the way of a removal that `htl shapes` did not write is left, and said, as the
/// overwrite guard says it; the other target of the module, which is its own, is removed.
#[test]
fn a_hand_written_file_in_the_way_of_a_removal_is_left_alone() {
    let root = project_with_extra("removal-guard");
    write(
        &root.join("src/shapes/extra.lua"),
        "return { mine = true }\n",
    );
    write(&root.join("src/extra.tl"), EXTRA_EMPTY);
    let out = htl(&root, &["shapes"]);
    assert_eq!(out.status.code(), Some(1), "{}", stderr(&out));
    let err = stderr(&out);
    assert!(
        err.contains(
            "shapes: src/shapes/extra.lua exists and was not written by htl shapes; move it aside\n"
        ),
        "{err}"
    );
    assert!(
        err.contains("shapes: removed types/shapes/extra.d.tl\n"),
        "{err}"
    );
    assert!(!err.contains("removed src/shapes/extra.lua"), "{err}");
    assert_eq!(
        read(&root.join("src/shapes/extra.lua")),
        "return { mine = true }\n"
    );
    assert!(!root.join("types/shapes/extra.d.tl").exists());
}

    /// One checked file: its module name, path relative to the project and check.
    struct Checked {
        module: String,
        rel: PathBuf,
        info: CheckInfo,
    }

    /// The module a file answers to: `geom/types.tl` is `geom.types`, `ev/init.tl` is `ev`,
    /// and `src/shop/app.tl` is `shop.app` (a project laid out as `htl new` does).
    fn module_of(rel: &str) -> String {
        let rel = rel.strip_prefix("src/").unwrap_or(rel);
        let stem = rel.strip_suffix(".tl").unwrap();
        stem.strip_suffix("/init").unwrap_or(stem).replace('/', ".")
    }

    /// A project of `.tl` files, each checked with the index kept.
    fn project(name: &str, files: &[(&str, &str)]) -> (TempDir, Vec<Checked>) {
        let root = tempdir("htl-core-rsgen", name);
        for (rel, text) in files {
            let path = root.join(rel);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(&path, text).unwrap();
        }
        let h = Htl::new().unwrap();
        h.add_path(&root).unwrap();
        if root.join("src").is_dir() {
            h.add_path(&root.join("src")).unwrap();
        }
        let checked = files
            .iter()
            .map(|(rel, _)| {
                let info = h.check_indexed(&root.join(rel)).unwrap();
                assert!(info.errors.is_empty(), "{rel}: {:?}", info.errors);
                Checked {
                    module: module_of(rel),
                    rel: PathBuf::from(rel),
                    info,
                }
            })
            .collect();
        (root, checked)
    }

    fn spec(modules: &[&str], types: &[(&str, &str)]) -> Spec {
        Spec {
            modules: modules.iter().map(|m| m.to_string()).collect(),
            types: types
                .iter()
                .map(|(k, v)| (k.to_string(), v.to_string()))
                .collect(),
            exports: Vec::new(),
        }
    }

    fn lower(checked: &[Checked], spec: &Spec) -> Rendered {
        let sources: Vec<Source> = checked
            .iter()
            .map(|c| Source {
                module: &c.module,
                rel_path: &c.rel,
                info: &c.info,
            })
            .collect();
        generate(&sources, spec, canon)
    }

    /// The file `generate` made of `files`, whole.
    fn text(name: &str, files: &[(&str, &str)], modules: &[&str]) -> String {
        text_with(name, files, modules, &[])
    }

    fn text_with(
        name: &str,
        files: &[(&str, &str)],
        modules: &[&str],
        types: &[(&str, &str)],
    ) -> String {
        let (_root, checked) = project(name, files);
        match lower(&checked, &spec(modules, types)) {
            Rendered::Text { text, .. } => text,
            other => panic!("not written: {other:#?}"),
        }
    }

    /// What `generate` refused with, as text, one line per problem.
    fn refused(name: &str, files: &[(&str, &str)], modules: &[&str]) -> Vec<String> {
        refused_with(name, files, modules, &[])
    }

    fn refused_with(
        name: &str,
        files: &[(&str, &str)],
        modules: &[&str],
        types: &[(&str, &str)],
    ) -> Vec<String> {
        let (_root, checked) = project(name, files);
        match lower(&checked, &spec(modules, types)) {
            Rendered::Refused { problems, .. } => problems.iter().map(|p| p.to_string()).collect(),
            other => panic!("not refused: {other:#?}"),
        }
    }


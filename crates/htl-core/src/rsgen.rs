/// What starts the first line of the file `htl rs` writes. A caller that is about to
/// overwrite a file checks that its first line starts with this, and leaves it alone
/// otherwise.
pub const HEADER: &str = "// Generated by htl rs";

/// The rule a note is said under.
const RULE: &str = "rust";

/// What a project asks `htl rs` for: `[rust]` of `htl.toml` without the key the command alone
/// reads (`out`).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Spec {
    /// The modules whose records and enums are written, by the name `require` takes. Empty
    /// is [`Rendered::Nothing`].
    pub modules: Vec<String>,
    /// `<module>.<type>.<field>` to the Rust type of that field; see the module doc.
    pub types: BTreeMap<String, String>,
    /// The modules whose returned record is written as a client over `htl::run::Instance`,
    /// by the name `require` takes; see the module doc's Exports. Empty is no client.
    pub exports: Vec<String>,
}

impl Spec {
    /// Whether there is nothing to write: what [`generate`] answers with
    /// [`Rendered::Nothing`], before it looks at a source.
    pub fn is_empty(&self) -> bool {
        self.modules.is_empty() && self.exports.is_empty()
    }
}

impl From<&crate::config::RustConfig> for Spec {
    /// `[rust]` without `out`: the one construction `htl rs` and `htl::teal_types!()` lower
    /// from, so that the two cannot ask different things of [`generate`].
    fn from(cfg: &crate::config::RustConfig) -> Self {
        Spec {
            modules: cfg.modules.clone(),
            types: cfg.types.clone(),
            exports: cfg.exports.clone(),
        }
    }
}

/// One of three outcomes, so "written with problems" is not a state.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Rendered {
    /// The file, and what is said and does not fail (a listed module that declares nothing).
    Text {
        /// The text of the file, starting with [`HEADER`].
        text: String,
        /// What is said and does not fail.
        notes: Vec<Diagnostic>,
    },
    /// Nothing written: one problem per site, the ones about the config first, then the
    /// ones in the files by file, line and column, and the notes gathered with them.
    Refused {
        /// What has no Rust type, or no Rust name.
        problems: Vec<Diagnostic>,
        /// What is said and does not fail.
        notes: Vec<Diagnostic>,
    },
    /// `modules` and `exports` are empty: there is nothing to write.
    Nothing,
}

/// Lower the records and enums of the listed modules of `sources`, and the clients of the
/// exported ones.
///
/// `sources` is every own module of the project, listed or not, each checked with the index
/// kept: a field of a listed module may name a type of an unlisted one, and has to be told
/// that it is one and not that it is outside the project. `canon` canonicalises the file of
/// a place, as [`RefTable::new`] takes it; this module reads no file, so the caller brings
/// that.
pub fn generate(sources: &[Source], spec: &Spec, canon: fn(&Path) -> PathBuf) -> Rendered {
    if spec.is_empty() {
        return Rendered::Nothing;
    }
    let listed: BTreeSet<String> = spec.modules.iter().cloned().collect();
    let exported: BTreeSet<String> = spec.exports.iter().cloned().collect();
    let refs = Refs {
        table: shapes::ref_table(sources, canon),
        listed: &listed,
    };
    let mut config_problems = Vec::new();
    let mut problems = Vec::new();
    let mut notes = Vec::new();

    // The modules to lower, and the ones to export, each in bytewise order of their names.
    let mut units: Vec<Unit> = Vec::new();
    for module in &listed {
        units.extend(unit_of(
            "modules",
            module,
            sources,
            &refs,
            &mut config_problems,
            &mut problems,
        ));
    }
    let mut exports: Vec<client::Export> = Vec::new();
    for module in &exported {
        let Some(unit) = unit_of(
            "exports",
            module,
            sources,
            &refs,
            &mut config_problems,
            &mut problems,
        ) else {
            continue;
        };
        match client::Export::new(unit) {
            Ok(export) => exports.push(export),
            Err(unit) => problems.push(Diagnostic::new(
                Severity::Error,
                unit.rel,
                1,
                1,
                format!(
                    "`{module}` is listed in [rust] exports and returns no record; a client is made of the functions of the record a module returns"
                ),
                None,
            )),
        }
    }
    // Every module that has a `pub mod`: a type may not take the name of one below it.
    let tree: Vec<&[&str]> = units
        .iter()
        .map(|u| u.segs.as_slice())
        .chain(exports.iter().map(|e| e.unit.segs.as_slice()))
        .collect();

    let overrides = resolve_types(spec, &units, &mut config_problems);

    // Lowered one module at a time; what each one says of itself stays with it.
    let mut blocks: Vec<Vec<String>> = Vec::new();
    let mut edges = Vec::new();
    let mut holds = Vec::new();
    for unit in &units {
        let mut l = Lowering {
            unit,
            units: &units,
            refs: &refs,
            overrides: &overrides,
            children: children_of(&unit.segs, &tree),
            cur: String::new(),
            problems: Vec::new(),
            edges: Vec::new(),
            reached: Vec::new(),
            holds: Vec::new(),
        };
        blocks.push(l.run());
        problems.append(&mut l.problems);
        edges.append(&mut l.edges);
        holds.append(&mut l.holds);
        if unit.cands.is_empty() {
            notes.push(Diagnostic::new(
                Severity::Warning,
                unit.rel.clone(),
                1,
                1,
                format!(
                    "`{}` is listed in [rust] modules and declares no record or enum",
                    unit.src.module
                ),
                Some(RULE),
            ));
        }
    }
    // The clients come after every type is lowered: what a record holds is what a method may
    // take or return.
    let lua = client::holding_lua_values(&holds);
    let mut clients: Vec<String> = Vec::new();
    for export in &exports {
        let made = export.lower(&units, &refs, &overrides, &tree, &lua);
        clients.push(made.text);
        problems.extend(made.problems);
        notes.extend(made.notes);
    }
    problems.extend(cycles(&edges));
    if !config_problems.is_empty() || !problems.is_empty() {
        problems.sort_by(|a, b| (&a.file, a.line, a.col).cmp(&(&b.file, b.line, b.col)));
        config_problems.append(&mut problems);
        return Rendered::Refused {
            problems: config_problems,
            notes,
        };
    }

    // The tree, and the text.
    let mut root = Node::default();
    for (i, u) in units.iter().enumerate() {
        root.at(&u.segs).unit = Some(i);
    }
    for (i, e) in exports.iter().enumerate() {
        root.at(&e.unit.segs).client = Some(i);
    }
    let mut sources_line: Vec<&str> = Vec::new();
    root.sources(&units, &exports, &mut sources_line);
    let mut text = format!(
        "{HEADER}. Do not edit: rerun `htl rs`.\n// Sources: {}\n",
        sources_line.join(", ")
    );
    for (name, node) in &root.children {
        if let Some(m) = node.render(name, 0, &blocks, &clients) {
            text.push('\n');
            text.push_str(&m);
            text.push('\n');
        }
    }
    Rendered::Text { text, notes }
}

/// A finding about the config: no file and no position, so it is said as its own sentence.
fn config_problem(message: String) -> Diagnostic {
    Diagnostic::new(Severity::Error, "", 0, 0, message, None)
}

/// What the table says of a declaration a type names.
enum Entry<'t> {
    /// A record or enum of a listed module: written, and nameable.
    Type(&'t ShapeRef),
    /// A declaration of an own module that is not in `[rust] modules`.
    NotListed(&'t str),
    /// A declaration of the project that is never lowered.
    NoShape(&'t NoShapeReason),
}

/// The table of [`shapes::ref_table`] and the modules that are written: together what
/// [`Entry`] says. [`RefEntry`] is what a declaration is; whether this run writes it is the
/// run's, so it is not a variant of it.
struct Refs<'l> {
    table: RefTable,
    listed: &'l BTreeSet<String>,
}

impl Refs<'_> {
    fn entry(&self, p: &Place) -> Option<Entry<'_>> {
        Some(match self.table.get(p)? {
            RefEntry::Shape(r) if self.listed.contains(&r.module) => Entry::Type(r),
            RefEntry::Shape(r) => Entry::NotListed(&r.module),
            RefEntry::NoShape(reason) => Entry::NoShape(reason),
        })
    }
}

/// One listed module to lower.
struct Unit<'a> {
    src: &'a Source<'a>,
    /// The project-relative path, as the header and the diagnostics spell it.
    rel: String,
    /// The module name's segments: `geom.types` is `geom`, `types`.
    segs: Vec<&'a str>,
    cands: Vec<Cand<'a>>,
    /// The aliases of the file.
    aliases: Vec<&'a Decl>,
}

/// The module `module` names, as `[rust] <key>` lists it: `None` once a problem has been said
/// (a segment that is no Rust name, no own module of that name, a file that kept no index).
fn unit_of<'a>(
    key: &str,
    module: &'a str,
    sources: &'a [Source<'a>],
    refs: &Refs,
    config_problems: &mut Vec<Diagnostic>,
    problems: &mut Vec<Diagnostic>,
) -> Option<Unit<'a>> {
    let segs: Vec<&str> = module.split('.').collect();
    if let Some(bad) = segs.iter().find(|s| !is_module_segment(s)) {
        config_problems.push(config_problem(format!(
            "[rust] {key}: `{module}`: `{bad}` cannot be the name of a Rust module"
        )));
        return None;
    }
    let Some(src) = sources.iter().find(|s| s.module == module) else {
        config_problems.push(config_problem(format!(
            "[rust] {key} lists `{module}`, which is no module of this project's own sources"
        )));
        return None;
    };
    let rel = rel_display(src.rel_path);
    let Some(decls) = src.info.types.declarations() else {
        problems.push(Diagnostic::new(
            Severity::Error,
            rel,
            1,
            1,
            format!("`{module}` kept no type index (the file did not parse); nothing to lower"),
            None,
        ));
        return None;
    };
    let cands = shapes::candidates(decls);
    let mut aliases = Vec::new();
    shapes::collect_aliases(decls, &mut aliases, &mut None, &refs.table);
    Some(Unit {
        src,
        rel,
        segs,
        cands,
        aliases,
    })
}

/// The names of the modules of `tree` directly below the module `segs`.
fn children_of<'a>(segs: &[&str], tree: &[&[&'a str]]) -> BTreeSet<&'a str> {
    let n = segs.len();
    tree.iter()
        .filter(|t| t.len() > n && t[..n] == *segs)
        .map(|t| t[n])
        .collect()
}

/// The declaration's path as a `[rust.types]` key spells it: the qualified name with the
/// returned record's name dropped when the returned record holds it.
fn type_path<'c>(c: &'c Cand) -> &'c str {
    if c.reachable {
        c.qual.split_once('.').map_or(c.qual.as_str(), |(_, p)| p)
    } else {
        &c.qual
    }
}

/// `[rust.types]` resolved: `(module, "<type>.<field>")` to the Rust type text, with a
/// problem for each key that matches no field, matches two, or has a value that is not a
/// Rust type.
fn resolve_types(
    spec: &Spec,
    units: &[Unit],
    problems: &mut Vec<Diagnostic>,
) -> HashMap<(String, String), String> {
    let fields: Vec<(&Unit, BTreeSet<String>)> = units
        .iter()
        .map(|u| {
            let keys = u
                .cands
                .iter()
                .filter(|c| c.is_record())
                .flat_map(|c| {
                    record_fields(c.decl)
                        .into_iter()
                        .map(move |(f, _)| format!("{}.{}", type_path(c), f.name))
                })
                .collect();
            (u, keys)
        })
        .collect();
    let mut out = HashMap::new();
    for (key, value) in &spec.types {
        let parsed = syn::parse_str::<syn::Type>(value);
        if let Err(e) = &parsed {
            problems.push(config_problem(format!(
                "[rust.types] \"{key}\" = \"{value}\" is not a Rust type: {e}"
            )));
        }
        let hits: Vec<(&Unit, String)> = fields
            .iter()
            .filter_map(|(u, keys)| {
                let rest = key
                    .strip_prefix(u.src.module)?
                    .strip_prefix('.')?
                    .to_string();
                keys.contains(&rest).then_some((*u, rest))
            })
            .collect();
        match hits.as_slice() {
            [] => problems.push(config_problem(format!(
                "[rust.types] \"{key}\" matches no field: a key is <module>.<type>.<field>, with the module listed in [rust] modules"
            ))),
            [(u, rest)] => {
                if parsed.is_ok() {
                    out.insert((u.src.module.to_string(), rest.clone()), value.trim().to_string());
                }
            }
            many => {
                let named: Vec<String> = many
                    .iter()
                    .map(|(u, rest)| format!("`{rest}` of module `{}`", u.src.module))
                    .collect();
                problems.push(config_problem(format!(
                    "[rust.types] \"{key}\" is ambiguous: it names {}",
                    named.join(" and ")
                )));
            }
        }
    }
    out
}

/// A type with the Rust it is made of.
struct Out {
    text: String,
    class: Class,
    /// Whether the type was `T | nil`: the nil is the caller's to place (the field, or the
    /// element of a container).
    nil: bool,
}

/// What a lowered type is, as far as a map key and the cycle rule ask.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Class {
    String,
    Integer,
    Number,
    Boolean,
    Any,
    Enum,
    Record,
    /// A `Vec` or a `HashMap`.
    Table,
}

impl Class {
    /// A type Rust's `HashMap` can be keyed by, and Lua's table can.
    fn is_key(self) -> bool {
        matches!(
            self,
            Class::String | Class::Integer | Class::Boolean | Class::Enum
        )
    }

    fn said(self) -> &'static str {
        match self {
            Class::Number => "`number`",
            Class::Any => "`any`",
            Class::Record => "a record",
            Class::Table => "a table",
            _ => "this type",
        }
    }
}

/// `Option<text>`, spelled in full.
fn option(text: &str) -> String {
    format!("::core::option::Option<{text}>")
}

/// A record that holds another (not behind a `Vec` or a `HashMap`): the edge a cycle of
/// them is made of.
struct Edge {
    from: (String, String),
    to: (String, String),
    file: String,
    line: usize,
    col: usize,
    site: String,
    written: String,
}

/// Each edge that closes a cycle, as a problem at the field that holds it.
fn cycles(edges: &[Edge]) -> Vec<Diagnostic> {
    let mut next: HashMap<&(String, String), Vec<&(String, String)>> = HashMap::new();
    for e in edges {
        next.entry(&e.from).or_default().push(&e.to);
    }
    let mut out = Vec::new();
    for e in edges {
        let mut seen = HashSet::new();
        let mut stack = vec![&e.to];
        let mut closes = false;
        while let Some(n) = stack.pop() {
            if *n == e.from {
                closes = true;
                break;
            }
            if seen.insert(n) {
                stack.extend(next.get(n).into_iter().flatten().copied());
            }
        }
        if closes {
            out.push(Diagnostic::new(
                Severity::Error,
                e.file.clone(),
                e.line,
                e.col,
                format!(
                    "`{}`: `{}` closes a cycle of records with no `{{T}}` or `{{K : V}}` in it, so the Rust struct would contain itself",
                    e.site, e.written
                ),
                None,
            ));
        }
    }
    out
}

/// A module of the generated tree.
#[derive(Default)]
struct Node {
    /// The listed module that is this node, an index into the units.
    unit: Option<usize>,
    /// The exported module that is this node, an index into the exports and their clients.
    client: Option<usize>,
    children: BTreeMap<String, Node>,
}

impl Node {
    /// The node at the module path `segs` below this one, made on the way.
    fn at(&mut self, segs: &[&str]) -> &mut Node {
        let mut node = self;
        for seg in segs {
            node = node.children.entry((*seg).to_string()).or_default();
        }
        node
    }

    /// The files of the modules at and below this node, the node's own first (once, when it
    /// is listed and exported both), then its children in order: the order the second line
    /// of the file names their sources in.
    fn sources<'u>(
        &self,
        units: &'u [Unit],
        exports: &'u [client::Export],
        out: &mut Vec<&'u str>,
    ) {
        match (self.unit, self.client) {
            (Some(u), _) => out.push(&units[u].rel),
            (None, Some(e)) => out.push(&exports[e].unit.rel),
            (None, None) => {}
        }
        for c in self.children.values() {
            c.sources(units, exports, out);
        }
    }

    /// The `pub mod` of this node at `depth` (four spaces each), or `None` when nothing is
    /// in it: a listed module that declares nothing has no module of its own. A module's
    /// types come first, then its client, then the modules below it.
    fn render(
        &self,
        name: &str,
        depth: usize,
        blocks: &[Vec<String>],
        clients: &[String],
    ) -> Option<String> {
        let mut items: Vec<String> = Vec::new();
        if let Some(u) = self.unit {
            items.extend(blocks[u].iter().map(|b| indent(b, depth + 1)));
        }
        if let Some(e) = self.client {
            items.push(indent(&clients[e], depth + 1));
        }
        for (n, c) in &self.children {
            items.extend(c.render(n, depth + 1, blocks, clients));
        }
        if items.is_empty() {
            return None;
        }
        let pad = "    ".repeat(depth);
        let attr = if depth == 0 {
            format!("{pad}{MODULE_ATTR}\n")
        } else {
            String::new()
        };
        Some(format!(
            "{attr}{pad}pub mod {name} {{\n{}\n{pad}}}",
            items.join("\n\n")
        ))
    }
}

/// An outer attribute on each top-level module: the generated names follow Teal's, not
/// Rust's, and a type may be unused by the host that includes the file.
const MODULE_ATTR: &str = "#[allow(non_snake_case, non_camel_case_types, dead_code, clippy::all)]";
const STRUCT_DERIVE: &str = "#[derive(Debug, Clone, PartialEq, ::htl::TealRecord)]";
const ENUM_DERIVE: &str =
    "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, ::htl::TealRecord)]";

fn indent(text: &str, depth: usize) -> String {
    let pad = "    ".repeat(depth);
    text.lines()
        .map(|l| {
            if l.is_empty() {
                String::new()
            } else {
                format!("{pad}{l}")
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// Rust words a Teal name may be that rustc's 2018 and 2021 lists do not have but 2024's
/// does: written raw, which every edition reads.
const RESERVED_LATER: [&str; 1] = ["gen"];

/// Names of primitives the mapping writes bare; a type of one of them would hide it.
const PRIMITIVES: [&str; 3] = ["i64", "f64", "bool"];

/// `name` as a Rust identifier, with `r#` in front of a keyword. `None` for what cannot be
/// one: not an identifier, or a word that is no identifier even raw (`self` `Self` `super`
/// `crate` `_`).
fn rust_ident(name: &str) -> Option<String> {
    if matches!(name, "_" | "self" | "Self" | "super" | "crate") || name.starts_with("r#") {
        return None;
    }
    if RESERVED_LATER.contains(&name) {
        return Some(format!("r#{name}"));
    }
    if syn::parse_str::<syn::Ident>(name).is_ok() {
        return Some(name.to_string());
    }
    syn::parse_str::<syn::Ident>(&format!("r#{name}"))
        .is_ok()
        .then(|| format!("r#{name}"))
}

/// A module segment: an identifier that is not a keyword.
fn is_module_segment(seg: &str) -> bool {
    rust_ident(seg).is_some_and(|r| !r.starts_with("r#"))
}

/// The variant a member makes: its words, split at what is not a letter or a digit, each
/// with a capital.
fn pascal(member: &str) -> String {
    member
        .split(|c: char| !c.is_alphanumeric())
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut cs = p.chars();
            let first = cs.next().into_iter().flat_map(char::to_uppercase);
            first.chain(cs).collect::<String>()
        })
        .collect()
}

/// The path to type `name` of module `target` from inside module `from`: the bare name in the
/// same module, `super::` for each segment above their common prefix, then the way down.
fn path_to(from: &[&str], target: &[&str], name: &str) -> String {
    let common = from.iter().zip(target).take_while(|(a, b)| a == b).count();
    let mut parts: Vec<&str> = vec!["super"; from.len() - common];
    parts.extend(&target[common..]);
    let name = rust_ident(name).unwrap_or_else(|| name.to_string());
    if parts.is_empty() {
        name
    } else {
        format!("{}::{name}", parts.join("::"))
    }
}

/// The lowering of one module.
struct Lowering<'a, 'r> {
    unit: &'r Unit<'a>,
    /// Every listed module: an alias a field names may be declared in another one.
    units: &'r [Unit<'a>],
    refs: &'r Refs<'r>,
    overrides: &'r HashMap<(String, String), String>,
    /// The names of the modules directly below this one that have a `pub mod` (listed or
    /// exported).
    children: BTreeSet<&'a str>,
    /// The name of the type being lowered: where an edge starts.
    cur: String,
    problems: Vec<Diagnostic>,
    edges: Vec<Edge>,
    /// What the types lowered since it was last emptied reached: the caller empties it,
    /// lowers, and reads it ([`Reached`]).
    reached: Vec<Reached>,
    /// What each record of the module reached through its fields.
    holds: Vec<Hold>,
}

/// What a lowered type is made of that the client of an export asks about: a Lua value, or
/// a record (which may hold one).
enum Reached {
    Any,
    Record {
        /// The module and name of the record, as an [`Edge`] names it.
        key: (String, String),
        /// The name as the Teal source wrote it.
        written: String,
    },
}

/// The record `from` and what its fields reach, through a `{T}`, a `{K : V}`, a `T | nil` or
/// directly. A field a `[rust.types]` entry types is not lowered and reaches nothing.
struct Hold {
    from: (String, String),
    reached: Vec<Reached>,
}

impl Lowering<'_, '_> {
    fn problem(&mut self, line: usize, col: usize, message: String) {
        self.problems.push(Diagnostic::new(
            Severity::Error,
            self.unit.rel.clone(),
            line,
            col,
            message,
            None,
        ));
    }

    fn marked(&mut self, marker: &str, kind: &str, d: &Decl, name: &str) -> bool {
        match shapes::marker_on(&self.unit.src.info.markers, marker, kind, d, name) {
            Ok(on) => on,
            Err(message) => {
                self.problem(d.name_line, d.name_col, message);
                false
            }
        }
    }

    /// The text of each type of the module, in position order. Empty when a problem was
    /// said: the caller discards it.
    fn run(&mut self) -> Vec<String> {
        let unit = self.unit;
        let mut names: Vec<String> = Vec::with_capacity(unit.cands.len());
        let mut by_name: HashMap<String, usize> = HashMap::new();
        for (i, c) in unit.cands.iter().enumerate() {
            let (line, col) = (c.decl.name_line, c.decl.name_col);
            let name = if PRIMITIVES.contains(&c.name.as_str()) {
                let message = format!(
                    "`{}` is named like the Rust primitive `{}`, which the generated types write bare",
                    c.qual, c.name
                );
                self.problem(line, col, message);
                c.name.clone()
            } else if let Some(n) = rust_ident(&c.name) {
                n
            } else {
                let message = format!("`{}` cannot be the name of a Rust type", c.qual);
                self.problem(line, col, message);
                c.name.clone()
            };
            let plain = name.strip_prefix("r#").unwrap_or(&name).to_string();
            if let Some(&first) = by_name.get(&plain) {
                let f = &unit.cands[first];
                let message = format!(
                    "`{}` (line {}) and `{}` (line {}) both lower to the Rust name `{plain}`; rename one",
                    f.qual, f.decl.name_line, c.qual, c.decl.name_line
                );
                self.problem(line, col, message);
            } else {
                by_name.insert(plain.clone(), i);
            }
            if self.children.contains(plain.as_str()) {
                // A child is a `pub mod` because it is listed, or only because it is exported.
                let n = unit.segs.len();
                let listed = self.units.iter().any(|u| {
                    u.segs.len() == n + 1 && u.segs[..n] == unit.segs[..] && u.segs[n] == plain
                });
                let how = if listed { "listed" } else { "exported" };
                let message = format!(
                    "`{}` has the name of the module `{}.{plain}`, which is {how}; a type and a module share one namespace in Rust",
                    c.qual, unit.src.module
                );
                self.problem(line, col, message);
            }
            names.push(name);
        }
        let mut out = Vec::with_capacity(unit.cands.len());
        for (i, name) in names.iter().enumerate() {
            out.push(self.declaration(i, name));
        }
        out
    }

    /// The text of candidate `i`, which is named `name` in Rust.
    fn declaration(&mut self, i: usize, name: &str) -> String {
        let unit = self.unit;
        let c = &unit.cands[i];
        self.cur = c.name.clone();
        let teal = &c.name;
        match c.kind {
            CandKind::Enum { members } => self.enumeration(c, name, teal, members),
            CandKind::Record => {
                self.reached.clear();
                let fields = self.record(c);
                self.holds.push(Hold {
                    from: (unit.src.module.to_string(), c.name.clone()),
                    reached: std::mem::take(&mut self.reached),
                });
                let mut s =
                    format!("{STRUCT_DERIVE}\n#[teal(name = \"{teal}\")]\npub struct {name} {{");
                if !fields.is_empty() {
                    s.push('\n');
                    for (n, t) in fields {
                        s.push_str(&format!("    pub {n}: {t},\n"));
                    }
                }
                s.push('}');
                s
            }
        }
    }

    fn enumeration(&mut self, c: &Cand, name: &str, teal: &str, members: &[String]) -> String {
        let d = c.decl;
        let mut variants: Vec<(String, &str)> = Vec::new();
        let mut seen: HashMap<String, &str> = HashMap::new();
        for m in members {
            if m.chars()
                .any(|ch| ch == '"' || ch == '\\' || ch.is_control())
            {
                let message = format!(
                    "`{}`: the member `{m}` holds a `\"`, a `\\` or a control character, which `#[teal(name = \"..\")]` cannot hold",
                    c.qual
                );
                self.problem(d.name_line, d.name_col, message);
                continue;
            }
            let Some(variant) = rust_ident(&pascal(m)) else {
                let message = format!(
                    "`{}`: the member `{m}` cannot be PascalCased into a Rust variant name",
                    c.qual
                );
                self.problem(d.name_line, d.name_col, message);
                continue;
            };
            let plain = variant.strip_prefix("r#").unwrap_or(&variant).to_string();
            if let Some(first) = seen.get(&plain) {
                let message = format!(
                    "`{}`: the members `{first}` and `{m}` both make the variant `{plain}`; rename one",
                    c.qual
                );
                self.problem(d.name_line, d.name_col, message);
                continue;
            }
            seen.insert(plain, m);
            variants.push((variant, m));
        }
        let mut s = format!("{ENUM_DERIVE}\n#[teal(name = \"{teal}\")]\npub enum {name} {{\n");
        for (variant, member) in variants {
            s.push_str(&format!(
                "    #[teal(name = \"{member}\")]\n    {variant},\n"
            ));
        }
        s.push('}');
        s
    }

    /// The fields of a record: the name, and the Rust type.
    fn record(&mut self, c: &Cand) -> Vec<(String, String)> {
        let (d, qual) = (c.decl, c.qual.clone());
        if let Some(TypeInfo::Record {
            interfaces,
            where_clause,
            ..
        }) = &d.info
        {
            if *interfaces {
                let message =
                    format!("`{qual}` takes fields from an interface (`is`); not lowered");
                self.problem(d.name_line, d.name_col, message);
            }
            match where_clause {
                Some(Where::Tag { .. }) | Some(Where::Other(_)) => {
                    let message = format!(
                        "`{qual}` has a `where` clause, so it is one member of a tagged union; not lowered"
                    );
                    self.problem(d.name_line, d.name_col, message);
                }
                None => {}
            }
        }
        if self.marked("extensible", "record", d, &qual) {
            let message = format!(
                "`{qual}` is marked `---@extensible`: a Rust struct drops the keys it does not know on the way back, so the record would lose them"
            );
            self.problem(d.name_line, d.name_col, message);
        }
        let is_struct = self.marked("struct", "record", d, &qual);
        let module = self.unit.src.module.to_string();
        let mut fields = Vec::new();
        for (f, ty) in record_fields(d) {
            let site = format!("{qual}.{}", f.name);
            let Some(name) = rust_ident(&f.name) else {
                let message = format!("`{site}`: `{}` cannot be the name of a Rust field", f.name);
                self.problem(f.line, f.col, message);
                continue;
            };
            let key = (module.clone(), format!("{}.{}", type_path(c), f.name));
            if let Some(text) = self.overrides.get(&key) {
                fields.push((name, text.clone()));
                continue;
            }
            let optional = self.marked("optional", "field", f, &site);
            let Some(out) = self.lower_ty(ty, f, &site, &mut Vec::new(), false) else {
                continue;
            };
            let text = if out.nil || optional || !is_struct {
                option(&out.text)
            } else {
                out.text
            };
            fields.push((name, text));
        }
        fields
    }

    /// The Rust type of `ty`. `None` once a problem has been said for it. `indirect` is
    /// whether a `Vec` or a `HashMap` is on the way from the field: a record named without
    /// one is inside this record.
    fn lower_ty(
        &mut self,
        ty: &TypeExpr,
        at: &Decl,
        site: &str,
        aliases: &mut Vec<String>,
        indirect: bool,
    ) -> Option<Out> {
        let prim = |text: &str, class| {
            Some(Out {
                text: text.to_string(),
                class,
                nil: false,
            })
        };
        match ty {
            TypeExpr::Prim(p) => match p {
                Prim::String => prim("::std::string::String", Class::String),
                Prim::Number => prim("f64", Class::Number),
                Prim::Integer => prim("i64", Class::Integer),
                Prim::Boolean => prim("bool", Class::Boolean),
                Prim::Any => {
                    self.reached.push(Reached::Any);
                    prim("::htl::mlua::Value", Class::Any)
                }
                Prim::Nil => self.no_type(at, site, "a type that is only `nil`"),
                Prim::Thread => self.no_type(at, site, "`thread`"),
                Prim::Userdata => self.no_type(at, site, "`userdata`"),
            },
            TypeExpr::Fn(_) => self.no_type(at, site, "a function or method field"),
            TypeExpr::Tuple(_) => self.no_type(at, site, "a tuple"),
            TypeExpr::Array(e) => {
                let e = self.lower_ty(e, at, site, aliases, true)?;
                // `Vec<Option<T>>` is what `#[derive(TealRecord)]` refuses: a nil inside a
                // Lua sequence is a hole that `#t` and `ipairs` stop at.
                if e.nil {
                    let message = format!(
                        "`{site}`: a sequence of a `nil`-able type has no Rust type; a nil inside a Lua sequence is a hole that `#t` and `ipairs` stop at"
                    );
                    self.problem(at.line, at.col, message);
                    return None;
                }
                Some(Out {
                    text: format!("::std::vec::Vec<{}>", e.text),
                    class: Class::Table,
                    nil: false,
                })
            }
            TypeExpr::Map(k, v) => {
                let k = self.lower_ty(k, at, site, aliases, true);
                let v = self.lower_ty(v, at, site, aliases, true);
                let (k, v) = (k?, v?);
                if k.nil || !k.class.is_key() {
                    let what = if k.nil {
                        "a `nil`-able type"
                    } else {
                        k.class.said()
                    };
                    let message = format!(
                        "`{site}`: a map keyed by {what} has no Rust type; a key is a `string`, an `integer`, a `boolean` or an enum of a listed module"
                    );
                    self.problem(at.line, at.col, message);
                    return None;
                }
                Some(Out {
                    text: format!("::std::collections::HashMap<{}, {}>", k.text, element(v)),
                    class: Class::Table,
                    nil: false,
                })
            }
            TypeExpr::Union(ms) => {
                // `T | nil` is a nilable `T`; nothing else is a union here.
                let rest: Vec<&TypeExpr> = ms
                    .iter()
                    .filter(|m| !matches!(m, TypeExpr::Prim(Prim::Nil)))
                    .collect();
                match rest.as_slice() {
                    [] => self.no_type(at, site, "a type that is only `nil`"),
                    [one] => {
                        let mut out = self.lower_ty(one, at, site, aliases, indirect)?;
                        out.nil |= rest.len() < ms.len();
                        Some(out)
                    }
                    _ => self.no_type(at, site, "a union other than `T | nil`"),
                }
            }
            TypeExpr::Nominal { names, declared } => {
                self.nominal(names, declared.as_ref(), at, site, aliases, indirect)
            }
            TypeExpr::Other(text) => self.no_type(
                at,
                site,
                &format!("`{text}` (a generic, a type variable, an empty table, ...)"),
            ),
        }
    }

    /// The problem of a type the mapping has no row for, said at the field.
    fn no_type(&mut self, at: &Decl, site: &str, what: &str) -> Option<Out> {
        self.problem(
            at.line,
            at.col,
            format!("`{site}`: {what} has no Rust type"),
        );
        None
    }

    fn nominal(
        &mut self,
        names: &[String],
        declared: Option<&Place>,
        at: &Decl,
        site: &str,
        aliases: &mut Vec<String>,
        indirect: bool,
    ) -> Option<Out> {
        let written = names.join(".");
        if let Some(p) = declared {
            let (unit, refs) = (self.unit, self.refs);
            match refs.entry(p) {
                Some(Entry::Type(r)) => {
                    let module: Vec<&str> = r.module.split('.').collect();
                    if r.record {
                        self.reached.push(Reached::Record {
                            key: (r.module.clone(), r.name.clone()),
                            written: written.clone(),
                        });
                    }
                    if r.record && !indirect {
                        self.edges.push(Edge {
                            from: (unit.src.module.to_string(), self.cur.clone()),
                            to: (r.module.clone(), r.name.clone()),
                            file: unit.rel.clone(),
                            line: at.line,
                            col: at.col,
                            site: site.to_string(),
                            written: written.clone(),
                        });
                    }
                    return Some(Out {
                        text: path_to(&unit.segs, &module, &r.name),
                        class: if r.record { Class::Record } else { Class::Enum },
                        nil: false,
                    });
                }
                Some(Entry::NotListed(module)) => {
                    let message = format!(
                        "`{site}`: `{written}` is declared in the module `{module}`, which is not in [rust] modules; list it, or give the field a type under [rust.types]"
                    );
                    self.problem(at.line, at.col, message);
                    return None;
                }
                Some(Entry::NoShape(reason)) => {
                    let message = match reason {
                        NoShapeReason::Returned(module) => format!(
                            "`{site}`: `{written}` is the record module `{module}` returns; a module has no Rust type"
                        ),
                        NoShapeReason::Interface => {
                            format!("`{site}`: `{written}` is an interface; it has no Rust type")
                        }
                    };
                    self.problem(at.line, at.col, message);
                    return None;
                }
                None => {}
            }
            // The alias may be declared in any listed module, not only the one being lowered
            // (which, for a client, need not be listed): `alias_in` matches only a place in
            // the file of the unit it is handed.
            let found = self.units.iter().chain([unit]).find_map(|u| {
                shapes::alias_in(&u.aliases, u.src.info.types.file(), &refs.table, names, p)
                    .map(|a| (format!("{}.{}", u.src.module, a.name), a))
            });
            if let Some((qualified, alias)) = found {
                if aliases.contains(&qualified) {
                    let message = format!("`{site}`: the alias `{written}` refers back to itself");
                    self.problem(at.line, at.col, message);
                    return None;
                }
                let Some(TypeInfo::Alias { ty }) = &alias.info else {
                    return None;
                };
                aliases.push(qualified);
                let out = self.lower_ty(ty, at, site, aliases, indirect);
                aliases.pop();
                return out;
            }
        }
        let message = format!(
            "`{site}`: `{written}` is declared outside the project's sources and has no Rust type"
        );
        self.problem(at.line, at.col, message);
        None
    }
}

/// The text of a map's value: a nilable one is an `Option` there.
fn element(o: Out) -> String {
    if o.nil { option(&o.text) } else { o.text }
}


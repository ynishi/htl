    #[test]
    fn the_types_table_is_held_to_what_it_says() {
        let geom = "local record M
   record types
      record X
         f: integer
      end
   end
end
return M
";
        let types = "local record M
   record X
      f: integer
   end
end
return M
";
        let files = [
            ("geom/init.tl", geom),
            ("geom/types.tl", types),
            ("ev.tl", EV),
        ];
        let problems = refused_with(
            "types-table",
            &files,
            &["ev", "geom", "geom.types"],
            &[
                ("ev.Event.nope", "u32"),
                ("ev.Event.at", "not a type"),
                ("geom.types.X.f", "u8"),
                ("nomodule.Event.at", "u32"),
            ],
        );
        let expected = [
            "[rust.types] \"ev.Event.at\" = \"not a type\" is not a Rust type: ",
            "[rust.types] \"ev.Event.nope\" matches no field: a key is <module>.<type>.<field>, with the module listed in [rust] modules",
            "[rust.types] \"geom.types.X.f\" is ambiguous: it names `types.X.f` of module `geom` and `X.f` of module `geom.types`",
            "[rust.types] \"nomodule.Event.at\" matches no field: a key is <module>.<type>.<field>, with the module listed in [rust] modules",
        ];
        assert!(problems[0].starts_with(expected[0]), "{problems:#?}");
        assert_eq!(&problems[1..4], &expected[1..], "{problems:#?}");
    }

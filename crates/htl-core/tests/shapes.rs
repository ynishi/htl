/// Two files that need each other's shapes cannot load: the groups are found.
#[test]
fn files_that_require_each_other_are_a_cycle() {
    let edges = |pairs: &[(&str, &[&str])]| -> Vec<(String, Vec<String>)> {
        pairs
            .iter()
            .map(|(m, to)| (m.to_string(), to.iter().map(|t| t.to_string()).collect()))
            .collect()
    };
    assert!(shapes::module_cycles(&edges(&[("a", &["b"]), ("b", &[])])).is_empty());
    assert_eq!(
        shapes::module_cycles(&edges(&[("a", &["b"]), ("b", &["a"])])),
        [["a", "b"]]
    );
    // Through a third; the bystanders that only require into the cycle are not in it.
    assert_eq!(
        shapes::module_cycles(&edges(&[
            ("c", &["a"]),
            ("a", &["b"]),
            ("b", &["d"]),
            ("d", &["a"]),
            ("e", &["c"]),
        ])),
        [["a", "b", "d"]]
    );
    // A module that is not among those written is not an edge.
    assert!(shapes::module_cycles(&edges(&[("a", &["gone"])])).is_empty());
}


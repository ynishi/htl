    #[cfg(all(feature = "pkg", feature = "dts"))]
    mod runtime_candidate {
        use htl_core::ModuleKind;
        use htl_core::resolve::{AnsweredBy, Candidate, Resolution, Status, Summary};
        use htl_core::shapes::lshape_runtime;

        fn resolution(rows: &[(&str, ModuleKind)]) -> Resolution {
            let candidates: Vec<Candidate> = rows
                .iter()
                .enumerate()
                .map(|(i, (path, kind))| Candidate {
                    order: i + 1,
                    path: (*path).to_string(),
                    dir: ".".into(),
                    kind: *kind,
                    status: if i == 0 {
                        Status::Read
                    } else {
                        Status::Shadowed
                    },
                    shadowed_by: (i > 0).then_some(1),
                    origin: None,
                })
                .collect();
            Resolution {
                module: "lshape".into(),
                read: candidates.first().map(|c| c.path.clone()),
                summary: Summary {
                    candidates: candidates.len(),
                    shadowed: candidates.len().saturating_sub(1),
                    ok: !candidates.is_empty(),
                },
                candidates,
                answered_by: AnsweredBy::Model,
                searched: Vec::new(),
                provided_by: None,
                provider: None,
                error: None,
            }
        }

        /// A case's name, the candidates in search order, and the path expected.
        type Case<'a> = (&'a str, Vec<(&'a str, ModuleKind)>, Option<&'a str>);

        fn runtime_path(rows: &[(&str, ModuleKind)]) -> Option<String> {
            lshape_runtime(&resolution(rows)).map(|c| c.path.clone())
        }

        #[test]
        fn the_runtime_is_the_first_candidate_that_is_not_a_declaration() {
            use ModuleKind::{Declaration, Lua, Source};
            let decl = ("types/lshape.d.tl", Declaration);
            let lua = ("src/lshape/init.lua", Lua);
            let tl = ("src/lshape.tl", Source);
            let cases: Vec<Case> = vec![
                ("declaration first, then Lua", vec![decl, lua], Some(lua.0)),
                ("Lua first", vec![lua, decl], Some(lua.0)),
                (
                    "the first of two implementations, in search order",
                    vec![decl, tl, lua],
                    Some(tl.0),
                ),
                ("only declarations", vec![decl], None),
                (
                    "two declarations",
                    vec![decl, ("other/lshape.d.tl", Declaration)],
                    None,
                ),
                ("nothing at all", vec![], None),
            ];
            for (name, rows, want) in cases {
                assert_eq!(runtime_path(&rows).as_deref(), want, "{name}");
            }
        }
    }

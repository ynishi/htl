/// The record the file returns is the module and is not lowered, whatever it holds; a
/// record of functions only that the file does not return is.
#[test]
fn the_returned_record_is_skipped_and_a_record_of_functions_is_not() {
    let p = Project::new(
        "returned",
        &[
            (
                "data.tl",
                "local record data
   VERSION: string
   record Req
      id: string
   end
end
return data
",
            ),
            (
                "fns.tl",
                "local record Callbacks
   done: function(string): boolean
   on_error: function(string)
end
local record fns
   VERSION: string
   hello: function(string): string
   record Inner
      cb: Callbacks
   end
end
function fns.hello(who: string): string
   return who
end
return fns
",
            ),
            (
                "self.tl",
                "local record self
   hello: function(string): string
end
function self.hello(who: string): string
   return who
end
return self
",
            ),
        ],
    );
    let (out, _) = written(p.check("data").alone());
    assert_eq!(
        out.lua,
        lua_head("data.tl")
            + "
M.Req = T.shape({
   id = T.string,
}, { open = false })

return M
"
    );
    let (out, notes) = written(p.check("fns").alone());
    assert_eq!(
        out.lua,
        lua_head("fns.tl")
            + "
M.Callbacks = T.shape({
   done = T.fn,
   on_error = T.fn,
}, { open = false })

M.Inner = T.shape({
   cb = M.Callbacks,
}, { open = false })

return M
"
    );
    // `Callbacks` is a top-level record the module does not hold: its shape is written and
    // the declaration cannot name it.
    assert_eq!(notes.len(), 1, "{notes:?}");
    assert!(
        notes[0].contains("`Callbacks` has a shape but no declaration entry"),
        "{notes:?}"
    );
    // Nothing to lower in a file that declares only its own module.
    assert_eq!(p.check("self").alone(), Lowered::Nothing);
}


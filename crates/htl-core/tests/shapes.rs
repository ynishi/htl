//! `htl_core::shapes`: the lowering of a checked file's records and enums to lshape shapes
//! and the `.d.tl` that types them. Every case checks a real file (`Htl::check_indexed`),
//! lowers it, and compares the generated text whole.

use htl_core::shapes::{self, Lowered, Output, RefTable, Source};
use htl_core::{CheckInfo, Htl};
use std::path::{Path, PathBuf};

mod common;

fn write(path: &Path, text: &str) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, text).unwrap();
}

fn canon(p: &Path) -> PathBuf {
    std::fs::canonicalize(p).unwrap_or_else(|_| p.to_path_buf())
}

/// A project directory of `.tl` files, checked with the index kept.
struct Project {
    root: common::TempDir,
    h: Htl,
}

/// One checked file: its module name, path and check.
struct Checked {
    module: String,
    rel: PathBuf,
    info: CheckInfo,
}

impl Project {
    fn new(name: &str, files: &[(&str, &str)]) -> Self {
        let root = common::tempdir("htl-core-shapes", name);
        for (rel, text) in files {
            write(&root.join(rel), text);
        }
        let h = Htl::new().unwrap();
        h.add_path(&root).unwrap();
        Self { root, h }
    }

    /// The file of module `module` (`main`, `knl.foo`), checked.
    fn check(&self, module: &str) -> Checked {
        let rel = PathBuf::from(format!("{}.tl", module.replace('.', "/")));
        let file = self.root.join(&rel);
        let info = self.h.check_indexed(&file).unwrap();
        assert!(info.errors.is_empty(), "{module}: {:?}", info.errors);
        Checked {
            module: module.to_string(),
            rel,
            info,
        }
    }
}

impl Project {
    /// The file of module `module`, checked with the index kept and its errors left in
    /// `info`: for a case the checker refuses by itself (the lowering is still told no).
    fn check_failing(&self, module: &str) -> Checked {
        let rel = PathBuf::from(format!("{}.tl", module.replace('.', "/")));
        let info = self.h.check_indexed(&self.root.join(&rel)).unwrap();
        assert!(!info.errors.is_empty(), "{module}: expected a check error");
        Checked {
            module: module.to_string(),
            rel,
            info,
        }
    }
}

impl Checked {
    fn source(&self) -> Source<'_> {
        Source {
            module: &self.module,
            rel_path: &self.rel,
            info: &self.info,
        }
    }

    fn lower(&self, refs: &RefTable) -> Lowered {
        shapes::lower(&self.source(), refs)
    }

    /// Lowered with only this file's own declarations known.
    fn alone(&self) -> Lowered {
        self.lower(&table(&[self]))
    }
}

/// A table with the declarations of every file in `files`.
fn table(files: &[&Checked]) -> RefTable {
    let mut refs = RefTable::new(canon);
    for f in files {
        refs.extend(shapes::declared_shapes(
            &f.module,
            f.info.types.declarations().unwrap(),
        ));
    }
    refs
}

/// The two files of a lowering that wrote them, and what it said.
fn written(l: Lowered) -> (Output, Vec<String>) {
    match l {
        Lowered::Written { output, notes, .. } => {
            (output, notes.iter().map(|n| n.to_string()).collect())
        }
        other => panic!("not written: {other:#?}"),
    }
}

/// The problems of a lowering that refused, as their text.
fn refused(l: Lowered) -> Vec<String> {
    match l {
        Lowered::Refused { problems, .. } => problems.iter().map(|p| p.to_string()).collect(),
        other => panic!("not refused: {other:#?}"),
    }
}

/// The first line of every generated file.
fn header(rel: &str) -> String {
    format!("-- Generated by htl shapes from {rel}. The record is the source; do not edit.\n")
}

fn lua_head(rel: &str) -> String {
    format!(
        "{}local T = require(\"lshape\").t\nlocal M = {{}}\n",
        header(rel)
    )
}

fn dtl_head(rel: &str, module: &str) -> String {
    format!(
        "{}-- Assert from another module: this file requires \"{module}\", so \"{module}\" cannot require it.\n",
        header(rel)
    )
}

/// Acceptance 1: the `Request` of the issue, as the two files.
#[test]
fn a_record_lowers_to_a_shape_and_a_declaration() {
    let p = Project::new(
        "request",
        &[(
            "main.tl",
            "local record M
   record Request
      id: string
      n: integer
      tags: {string}   ---@optional
   end
end
return M
",
        )],
    );
    let (out, notes) = written(p.check("main").alone());
    assert_eq!(
        out.lua,
        lua_head("main.tl")
            + "
M.Request = T.shape({
   id = T.string,
   n = T.integer,
   tags = T.array_of(T.string):is_optional(),
}, { open = false })

return M
"
    );
    assert_eq!(
        out.dtl,
        dtl_head("main.tl", "main")
            + "local lshape = require(\"lshape\")
local type main = require(\"main\")
local record shapes_main
   Request: lshape.Schema<main.Request>
end
return shapes_main
"
    );
    assert!(notes.is_empty(), "{notes:?}");
}


/// Two fields on one line: a marker is found by the name of the field the census put it on,
/// not by the line, so it makes one field optional and not both.
#[test]
fn a_marker_is_matched_by_name_and_not_by_line() {
    let p = Project::new(
        "oneline",
        &[(
            "main.tl",
            "local record M
   record R
      first: string   second: integer   ---@optional
      third: boolean
   end
end
return M
",
        )],
    );
    let c = p.check("main");
    let named: Vec<&str> = c
        .info
        .markers
        .iter()
        .filter(|m| m.marker == "optional")
        .map(|m| m.name.as_str())
        .collect();
    assert_eq!(named.len(), 1, "{named:?}");
    let only = named[0].rsplit('.').next().unwrap().to_string();
    let (out, _) = written(c.alone());
    let optional: Vec<&str> = out
        .lua
        .lines()
        .filter(|l| l.ends_with(":is_optional(),"))
        .collect();
    assert_eq!(optional.len(), 1, "{}", out.lua);
    assert!(
        optional[0].starts_with(&format!("   {only} = ")),
        "{optional:?}"
    );
}

